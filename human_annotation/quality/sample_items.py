"""
Sample the ValuePrism opinions generated by llama-3.3-70b for the human quality check:
stratified over the target stance, at most one opinion per situation. Stance is balanced in
the generation file, so the overall rate needs no reweighting.

Usage:
    python -m human_annotation.quality.sample_items
"""
import argparse
from pathlib import Path

import numpy as np
import pandas as pd

from utils.data_utils import opinions_path

HERE = Path(__file__).resolve().parent
STANCES = ["Supports", "Opposes", "Either"]
ITEM_COLUMNS = ["sample_id", "situation_id", "text_id", "situation", "stance", "vp_vrd", "vp_vrd_value",
                "vp_explanation", "text", "generation_model"]


def parse_args():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--generations_csv", type=Path, default=opinions_path("valueprism"))
    parser.add_argument("--n_items", type=int, default=150)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--output_csv", type=Path, default=HERE / "samples" / "items.csv")
    return parser.parse_args()


def stratified_sample(gens, n_items, rng):
    quota = {s: n_items // len(STANCES) for s in STANCES}
    for s in rng.permutation(STANCES)[: n_items % len(STANCES)]:
        quota[s] += 1
    # Each situation is given to one stance up front, so that no stance runs out of situations.
    situations = rng.permutation(gens["situation_id"].unique())
    if len(situations) < n_items:
        raise ValueError(f"Only {len(situations)} situations for {n_items} items.")
    chosen, start = [], 0
    for stance in STANCES:
        own = set(situations[start:start + quota[stance]])
        start += quota[stance]
        candidates = gens[(gens["stance"] == stance) & gens["situation_id"].isin(own)]
        chosen.append(candidates.iloc[rng.permutation(len(candidates))].drop_duplicates("situation_id"))
    sample = pd.concat(chosen)
    return sample.iloc[rng.permutation(len(sample))].reset_index(drop=True)


def main():
    args = parse_args()
    gens = pd.read_csv(args.generations_csv)
    gens["text"] = gens["text"].astype(str).str.strip()
    sample = stratified_sample(gens, args.n_items, np.random.default_rng(args.seed))
    sample["sample_id"] = [f"Q{i + 1:03d}" for i in range(len(sample))]
    args.output_csv.parent.mkdir(parents=True, exist_ok=True)
    sample[ITEM_COLUMNS].to_csv(args.output_csv, index=False)
    print(pd.crosstab(sample["stance"], sample["vp_vrd"], margins=True).to_string())
    print(f"Saved {len(sample)} items to {args.output_csv}")


if __name__ == "__main__":
    main()
